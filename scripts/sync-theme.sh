#!/bin/sh
# Regenerates internal/web/static/theme.css from the org website's design
# tokens, so voodoo's colors, shadows and borders track the shared design
# system. The website (Tailwind v4) keeps its tokens in an `@theme static { }`
# block; this copies every `--name: value;` declaration in it into a plain
# `:root { }` block that style.css reads. Nothing else is copied.
#
#   usage: scripts/sync-theme.sh [path/to/website]   (default ../0xD34DC0D3/website)
set -eu

site=${1:-../0xD34DC0D3/website}
src="$site/src/styles/global.css"
out=internal/web/static/theme.css

[ -f "$src" ] || { echo "sync-theme: $src not found" >&2; exit 1; }

rev=$(git -C "$site" rev-parse --short HEAD 2>/dev/null || echo unknown)

{
	echo "/* GENERATED by scripts/sync-theme.sh from 0xD34DC0D3/website@$rev"
	echo "   (src/styles/global.css). Do not edit; re-run the script instead. */"
	echo
	echo ":root {"
	awk '
		/@theme/ { in_theme = 1; depth = 0 }
		in_theme {
			n = gsub(/\{/, "{"); depth += n
			if ($0 ~ /^[ \t]*--[a-z0-9-]+:/ && depth == 1) { sub(/^[ \t]+/, ""); print "  " $0 }
			m = gsub(/\}/, "}"); depth -= m
			if (depth == 0 && m > 0) in_theme = 0
		}
	' "$src"
	echo "}"
} >"$out"

echo "sync-theme: wrote $out from $site@$rev"
